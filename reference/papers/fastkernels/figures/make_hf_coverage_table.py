#!/usr/bin/env python3
"""HF Transformers coverage table (appendix) from the raw audit table.

Reads figures/data/hf_coverage_raw.tex (the audit's longtable plus its lists of pending and
excluded architectures), drops links and duplicate architectures, sorts alphabetically, marks
entries whose relative L2 exceeds the dtype threshold, and writes tables/hf_coverage.tex and
figures/data/hf_coverage.json (entries, lists, and coverage counts).
"""

from __future__ import annotations

import json
import re
from pathlib import Path

PAPER_DIR = Path(__file__).resolve().parent.parent
RAW = PAPER_DIR / "figures" / "data" / "hf_coverage_raw.tex"
# Relative L2 (%) thresholds per dtype; mixed-precision entries use their most permissive dtype.
# Architectures the HF audit flags only because HF's implementation differs from the version in the
# reference library FastKernels pins; counted as supported (marked * in the table).
PINNED_VERSION = {"kimi_linear": "vLLM", "rwkv": "FLA's RWKV-7", "sam3_video": "the SAM~3 release",
                  "timm_wrapper": "timm"}
THRESHOLDS = {"fp32": 0.01, "fp16": 0.5, "bf16": 2.0, "fp8": 5.0, "fp4": 20.0, "mxfp4": 20.0, "int4": 20.0}


def strip(cell: str) -> str:
    cell = cell.strip()
    for pat in (r"\\nolinkurl\{([^{}]*)\}", r"\\HF\{([^{}]*)\}", r"\\href\{[^{}]*\}\{([^{}]*)\}", r"\\Arch\{([^{}]*)\}"):
        cell = re.sub(pat, r"\1", cell)
    return cell.strip()


def value(rel: str) -> float:
    m = re.search(r"([0-9.]+)\\!\\times\\!10\^\{(-?[0-9]+)\}", rel)
    return float(m.group(1)) * 10 ** int(m.group(2)) if m else float(rel)


def parse() -> tuple[list[dict], dict[str, list[str]]]:
    raw = RAW.read_text()
    body = raw[raw.index("\\endlastfoot") + len("\\endlastfoot"):raw.index("\\end{longtable}")]
    entries, seen = [], set()
    for row in body.split("\\\\"):
        row = re.sub(r"^\[[^\]]*\]", "", row.strip()).strip()
        if not row:
            continue
        cells = re.split(r"\s*&\s*", row)
        for k in range(0, len(cells) - 3, 4):
            arch, model, dtype, rel = (strip(c) for c in cells[k:k + 4])
            if arch and arch not in seen:
                seen.add(arch)
                lim = max(THRESHOLDS[d] for d in dtype.split("/"))
                entries.append({"arch": arch, "model": model, "dtype": dtype, "rel_l2": rel,
                                "rel_l2_value": value(rel), "threshold": lim, "within": value(rel) <= lim})
    tail = raw[raw.index("Pending and excluded"):]
    lists = {re.sub(r"\s*\(\d+\)\.?$", "", m.group(1)): re.findall(r"\\Arch\{([^}]*)\}", m.group(2))
             for m in re.finditer(r"\\paragraph\{([^}]*)\}\s*(.*?)(?=\\paragraph|\\end\{document\})", tail, re.S)}
    for e in entries:
        e["pinned_version"] = e["arch"] in PINNED_VERSION
    for arch in PINNED_VERSION:
        for name, archs in lists.items():
            if arch in archs:
                archs.remove(arch)
                entries.append({"arch": arch, "model": "---", "dtype": "---", "rel_l2": "---", "rel_l2_value": None,
                                "threshold": None, "within": False, "pinned_version": True})
    return sorted(entries, key=lambda e: e["arch"].lower()), lists


def cell_arch(e: dict) -> str:
    return f"\\nolinkurl{{{e['arch']}}}" + ("$^{*}$" if e["pinned_version"] else "")


def cell_model(e: dict) -> str:
    if e["model"] == "---":
        return "---"
    if " " not in e["model"]:
        return f"\\nolinkurl{{{e['model']}}}"
    return re.sub(r"([_&%#$])", r"\\\1", e["model"])  # plain text (e.g. "Constructor defaults")


def cell_rel(e: dict) -> str:
    over = e["rel_l2_value"] is not None and not e["within"]
    return e["rel_l2"] + ("$^\\dagger$" if over else "")


def main() -> None:
    entries, lists = parse()
    head = ("Architecture & HF model & \\texttt{dtype} & Rel.\\ L2 (\\%) \\\\")
    col = (">{\\raggedright\\arraybackslash}p{.28\\linewidth}>{\\raggedright\\arraybackslash}p{.45\\linewidth}"
           ">{\\raggedright\\arraybackslash}p{.1\\linewidth}>{\\raggedleft\\arraybackslash}p{.13\\linewidth}")
    lines = ["% Generated by figures/make_hf_coverage_table.py. Do not edit by hand.",
             "\\begingroup\\scriptsize\\setlength{\\tabcolsep}{2pt}\\setlength{\\LTleft}{0pt}\\setlength{\\LTright}{0pt}",
             f"\\begin{{longtable}}{{@{{}}{col}@{{}}}}",
             "\\caption{\\textbf{HuggingFace Transformers coverage audit} (commit \\texttt{89b6b17}): every architecture "
             "implemented on \\fastkernels{} and the relative L2 difference (\\%) of its output from native HF. "
             "$^\\dagger$: above the threshold for its \\texttt{dtype}. $^{*}$: flagged only because HF differs from the "
             "version \\fastkernels{} pins; counted as supported.}\\label{tab:hf-coverage}\\\\",
             "\\toprule", head, "\\midrule", "\\endfirsthead",
             "\\multicolumn{4}{@{}l}{\\tablename~\\thetable\\ (continued)}\\\\[2pt]", "\\toprule", head, "\\midrule",
             "\\endhead", "\\bottomrule", "\\endfoot"]
    for e in entries:
        lines.append(" & ".join((cell_arch(e), cell_model(e), e["dtype"], cell_rel(e))) + " \\\\")
    lines += ["\\end{longtable}", "\\endgroup", ""]
    (PAPER_DIR / "tables" / "hf_coverage.tex").write_text("\n".join(lines))
    lists = {k: sorted(v) for k, v in lists.items()}
    measured = [e for e in entries if e["rel_l2_value"] is not None]
    within = sum(e["within"] for e in entries)
    over = [e["arch"] for e in measured if not e["within"]]
    pinned = [e["arch"] for e in entries if e["pinned_version"]]
    supported = sum(e["within"] or e["pinned_version"] for e in entries)
    new_ops, hf_issues, excluded = (lists["Models requiring new operations"], lists["HF reference issues"],
                                    lists["Excluded from audit"])
    total = len(entries) + len(new_ops) + len(hf_issues)
    counts = {"table_rows": len(entries), "within_threshold": within, "over_threshold": len(over),
              "pinned_version": len(pinned), "supported": supported, "requiring_new_operations": len(new_ops),
              "hf_reference_issues": len(hf_issues), "excluded": len(excluded), "denominator": total,
              "coverage_pct": round(100 * supported / total, 1)}
    fmt = lambda names: ", ".join(f"\\nolinkurl{{{n}}}" for n in names)  # noqa: E731
    notes = "; ".join(f"{PINNED_VERSION[a]} for \\nolinkurl{{{a}}}" for a in sorted(PINNED_VERSION))
    summary = [
        "% Generated by figures/make_hf_coverage_table.py. Do not edit by hand.",
        f"Table~\\ref{{tab:hf-coverage}} lists {len(entries)} architectures: {within} are within their threshold, "
        f"{len(over)} run but exceed it (marked $^\\dagger$), and {len(pinned)} (marked $^{{*}}$) are flagged by the HF audit "
        "only because the HF implementation differs from the version in the reference library \\fastkernels{} pins "
        f"({notes}); we count these as supported because \\fastkernels{{}} supports a valid version of each.",
        "The remaining architectures fall in three groups.",
        f"\\emph{{Requiring new operations}} ({len(new_ops)}): {fmt(new_ops)}.",
        f"\\emph{{HF reference issues}} ({len(hf_issues)}), where the native HF implementation itself fails, so no "
        f"reference output exists: {fmt(hf_issues)}.",
        f"\\emph{{Excluded}} ({len(excluded)}): generic wrappers that compose other architectures and have no modeling "
        f"code of their own: {fmt(excluded)}.",
        f"Coverage is therefore \\textbf{{{counts['coverage_pct']}\\% ({supported}/{total})}}: excluding the wrappers, "
        "the architectures above their threshold (unless marked $^{*}$), those that require new operations, and those "
        "without a working HF reference count as unsupported.", ""]
    (PAPER_DIR / "tables" / "hf_coverage_summary.tex").write_text("\n".join(summary))
    (PAPER_DIR / "figures" / "data" / "hf_coverage.json").write_text(
        json.dumps({"counts": counts, "lists": lists, "entries": entries}, indent=1))
    print(json.dumps(counts, indent=1))
    print("over threshold:", over, "| pinned-version:", pinned)

if __name__ == "__main__":
    main()
