#!/usr/bin/env python3
"""Baseline drift table (appendix): vLLM 0.18.0 -> 0.26.0 on H200 and B200.

Inputs are the drift.json files written by ``python -m fastkernels.validate.drift`` (the
coefficients the baseline-drift CI job computes) on the canonical runs of the vLLM version
ablations (Alexsssu--fastkernels-{h200,b200}-vllm-ablation). Writes tables/baseline_drift.tex.
"""

import json
from pathlib import Path

PAPER_DIR = Path(__file__).resolve().parent.parent
GPUS = [("H200", "drift_h200_vllm018_026.json"), ("B200", "drift_b200_vllm018_026.json")]
FAMILIES = ["LLM (dense + MoE)", "Linear attention / SSM / hybrid", "Multimodal / VLM", "Audio"]


def main() -> None:
    data = {g: json.loads((PAPER_DIR / "figures" / "data" / f).read_text()) for g, f in GPUS}
    fx = lambda x: f"{x:.2f}$\\times$"  # noqa: E731
    lines = ["% Generated by figures/make_drift_table.py. Do not edit by hand.",
             "\\begin{tabular}{@{}lr rr rr@{}}", "\\toprule",
             " & & \\multicolumn{2}{c}{\\textbf{H200}} & \\multicolumn{2}{c}{\\textbf{B200}} \\\\",
             "\\cmidrule(lr){3-4}\\cmidrule(lr){5-6}",
             "Model family & $n$ & Thr. & Lat. & Thr. & Lat. \\\\", "\\midrule"]
    for fam in FAMILIES:
        h, b = data["H200"]["families"][fam], data["B200"]["families"][fam]
        name = fam.replace("&", "\\&")
        lines.append(f"{name} & {h['n']} & {fx(h['throughput'])} & {fx(h['latency'])} & "
                     f"{fx(b['throughput'])} & {fx(b['latency'])} \\\\")
    h, b = data["H200"]["median_model"], data["B200"]["median_model"]
    lines += ["\\midrule", f"Median model & {len(data['H200']['models'])} & {fx(h['throughput'])} & "
              f"{fx(h['latency'])} & {fx(b['throughput'])} & {fx(b['latency'])} \\\\",
              "\\bottomrule", "\\end{tabular}", ""]
    (PAPER_DIR / "tables" / "baseline_drift.tex").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
