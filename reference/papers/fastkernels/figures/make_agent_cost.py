#!/usr/bin/env python3
"""Agent cost table: generation time and tokens per agent and campaign.

Recomputed from each run's raw per-operator logs
(``<run>/<ind|seq>/agent_workspaces/L*/<op>/metrics/{wall,usage}.jsonl``), not from
``metrics-summary.json``: the summary keeps only an operator's first ``op`` event, which
undercounts operators that were relaunched (e.g. 64 Codex operators whose first launch failed).

* time: sum of the operator's ``op`` events (every launch); operators without one (4 AKO
  operators) use the span of all their logged events. Operators run in parallel, so the
  total is agent-hours, not campaign wall-clock time.
* tokens: as reported by each agent's CLI/API. Claude: input + output + cache creation +
  cache reads; Codex: its reported total (input incl. cached + output incl. reasoning);
  Dr. Kernel: prompt + completion of its local model (no caching). KDA counts both its Claude
  and Codex sessions.

Writes tables/agent_cost.tex and figures/data/agent_cost.json.
"""

from __future__ import annotations

import json
import statistics as st
from pathlib import Path

PAPER_DIR = Path(__file__).resolve().parent.parent
FK_ROOT = PAPER_DIR.parent
AGENTS = [
    ("Dr.~Kernel", "drkernel-b200-20260919/campaign"),
    ("Claude Code", "claude-fk-runs"),
    ("KDA", "kda-fk-runs"),
    ("AKO", "ako4x-fk-runs"),
    ("Codex", "codex-fk-runs"),
]
MODES = [("ind", "Independent"), ("seq", "Sequential")]


def rows(p: Path) -> list[dict]:
    return [json.loads(l) for l in p.read_text().splitlines() if l.strip()] if p.is_file() else []


def op_cost(op: Path) -> dict:
    walls, usage = rows(op / "metrics" / "wall.jsonl"), rows(op / "metrics" / "usage.jsonl")
    opev = [r for r in walls if r.get("event") == "op"]
    if opev:
        sec = sum(r.get("elapsed_sec") or 0 for r in opev)
    else:
        t0 = [r["t0"] for r in walls if r.get("t0")]
        t1 = [r["t1"] for r in walls if r.get("t1")]
        sec = max(t1) - min(t0) if t0 and t1 else 0.0
    c = {"sec": sec, "total": 0, "out": 0, "cached": 0}
    codex = [r for r in usage if r.get("source") == "codex"]
    codex = [r for r in codex if r.get("session_id")] or codex  # prefer session logs over scrapes
    for r in usage:
        if "prompt_tokens" in r:  # Dr. Kernel
            c["total"] += int(r["prompt_tokens"]) + int(r.get("completion_tokens") or 0)
            c["out"] += int(r.get("completion_tokens") or 0)
    for r in [r for r in usage if r.get("source") == "claude"] + codex:
        c["total"] += int(r.get("total_tokens") or r.get("codex_tokens") or 0)
        c["out"] += int(r.get("output_tokens") or 0)
        c["cached"] += int(r.get("cache_read_input_tokens") or 0)
    return c


def main() -> None:
    data, lines = {}, [
        "\\begin{tabular}{@{}ll r rr rrr@{}}",
        "\\toprule",
        " & & & \\multicolumn{2}{c}{\\textbf{Agent-hours}} & \\multicolumn{3}{c}{\\textbf{Tokens}} \\\\",
        "\\cmidrule(lr){4-5}\\cmidrule(lr){6-8}",
        "Agent & Campaign & Ops & Total & Median/op & Total (B) & Output (M) & Cached (\\%) \\\\",
        "\\midrule",
    ]
    for x, (name, rd) in enumerate(AGENTS):
        if x:
            lines.append("\\midrule")
        for y, (mode, label) in enumerate(MODES):
            ops = [op_cost(w.parent.parent) for w in
                   sorted((FK_ROOT / rd / mode).glob("agent_workspaces/L*/*/metrics/wall.jsonl"))]
            t = {k: sum(o[k] for o in ops) for k in ("sec", "total", "out", "cached")}
            med = st.median(o["sec"] for o in ops) / 3600
            data[f"{name}|{mode}"] = {"ops": len(ops), "agent_hours": t["sec"] / 3600, "median_hours_per_op": med,
                                      "tokens_total": t["total"], "tokens_output": t["out"], "tokens_cached": t["cached"]}
            cached = f"{100 * t['cached'] / t['total']:.0f}" if t["total"] and t["cached"] else "---"
            cell = f"\\multirow{{2}}{{*}}{{{name}}}" if y == 0 else ""
            lines.append(f"{cell} & {label} & {len(ops)} & {t['sec'] / 3600:,.0f} & {med:.2f} & "
                         f"{t['total'] / 1e9:.2f} & {t['out'] / 1e6:.1f} & {cached} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", ""]
    (PAPER_DIR / "tables" / "agent_cost.tex").write_text(
        "% Generated by figures/make_agent_cost.py. Do not edit by hand.\n" + "\n".join(lines))
    (PAPER_DIR / "figures" / "data" / "agent_cost.json").write_text(json.dumps(data, indent=1))
    for k, v in data.items():
        print(f"{k:24} ops={v['ops']:3} agent-h={v['agent_hours']:7.0f} med={v['median_hours_per_op']:.2f} "
              f"tok={v['tokens_total'] / 1e9:.2f}B out={v['tokens_output'] / 1e6:.1f}M")
    print("wrote tables/agent_cost.tex, figures/data/agent_cost.json")


if __name__ == "__main__":
    main()
